#!/usr/bin/env python3
"""Generate the undo data the toolbox needs from the playbook's YAML.

Reads playbook.conf and Configuration/Tasks/*.yml and writes:

  Executables/ClaudePlaybook/Internal/manifest.json
      Every registry value, service start type and scheduled task the playbook
      changes, grouped by feature-page option (or, for changes that always
      apply, by task file). Backup.ps1 records their original values before
      anything runs; Restore.ps1 puts them back.
  Executables/ClaudePlaybook/Undo one change/Undo - <title>.cmd
      One launcher per group.
  Configuration/Tasks/converge.yml
      For each option, a Restore run with '!option', so an option that is
      turned off on a later run of the playbook is undone (only values that
      still hold what the playbook set are touched).

It also refuses actions the toolbox cannot undo (rule 5 in CLAUDE.md): key
deletes, service or task deletes, file and component removal.

Usage: python3 tools/manifest.py [--check] [playbook_dir]
  --check  exit 1 if the generated files on disk are out of date.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import Loader, TaggedAction  # noqa: E402

GENERATED_HEADER = "# Generated by tools/manifest.py. Do not edit; run the script instead.\n"

# Short names for the undo launchers and logs. Groups are feature-page
# options, or task file stems for changes that always apply. A group missing
# here falls back to its option text.
TITLES = {
    "privacy": "Privacy and telemetry settings",
    "services": "Telemetry services",
    "scheduled-tasks": "Telemetry scheduled tasks",
    "updates": "Delivery Optimization",
    "remove-bloat-apps": "Bloat apps",
    "remove-copilot": "Copilot and Recall",
    "remove-phonelink": "Phone Link",
    "remove-xbox": "Xbox and Game Bar",
    "remove-edge": "Edge removal",
    "remove-onedrive": "OneDrive removal",
    "browser-brave": "Brave policies",
    "defender-disable": "Defender off",
    "updates-notify": "Windows Update asks first",
    "wu-no-drivers": "No drivers from Windows Update",
    "gaming-power-plan": "Gaming power plan",
    "gaming-latency": "Foreground priority",
    "gaming-mouse": "Mouse acceleration off",
    "gaming-stickykeys": "Sticky Keys shortcut off",
    "disable-hibernation": "Hibernation and Fast Startup off",
    "gaming-memory-integrity": "Memory Integrity off",
    "dev-long-paths": "Long file paths",
    "dev-python-alias": "Python Store shortcuts removed",
    "dev-telemetry-optout": "dotnet and PowerShell telemetry opt-out",
    "dev-wsl": "WSL features",
    "ui-classic-menu": "Classic right-click menu",
    "ui-explorer": "File Explorer settings",
    "ui-taskbar": "Taskbar settings",
    "ui-taskbar-left": "Taskbar on the left",
    "ui-dark": "Dark mode",
}

# Values the toolbox reads to decide an undo step but never writes.
OBSERVE_ONLY = [
    {"group": "disable-hibernation", "path": r"HKLM\SYSTEM\CurrentControlSet\Control\Power",
     "name": "HibernateEnabled", "type": "REG_DWORD"},
]

# Groups whose undo needs a script step in Restore.ps1 (Invoke-GroupHandler).
# Keep in sync with that function.
HANDLERS = {"gaming-power-plan", "disable-hibernation", "dev-wsl", "dev-python-alias",
            "remove-bloat-apps", "remove-xbox", "remove-copilot", "remove-phonelink",
            "remove-edge"}
# Handlers that also run when an option is turned off on a later run.
CONVERGE_HANDLERS = {"gaming-power-plan", "disable-hibernation", "dev-wsl"}

NOT_REVERSIBLE = {
    "registryKey": "deletes or creates whole keys; use !registryValue",
    "file": "deletes files",
    "systemPackage": "removes Windows components",
}

errors = []


def load_options(root):
    tree = ET.parse(root / "playbook.conf").getroot()
    options = {}
    for opt in tree.iterfind("FeaturePages/*/Options/*"):
        name = (opt.findtext("Name") or "").strip()
        text = (opt.findtext("Text") or name).strip()
        if name:
            options[name] = text
    return options


def norm_data(rtype, data, where):
    if rtype in ("REG_DWORD", "REG_QWORD"):
        s = str(data).strip()
        try:
            v = int(s, 16) if s.lower().startswith("0x") else int(s)
        except ValueError:
            errors.append(f"{where}: {rtype} data '{data}' is not a number")
            return 0
        bits = 32 if rtype == "REG_DWORD" else 64
        if not -(1 << (bits - 1)) <= v < (1 << bits):
            errors.append(f"{where}: {rtype} data {v} is out of range")
        return v
    if rtype == "REG_MULTI_SZ":
        return data if isinstance(data, list) else [str(data)]
    if rtype in ("REG_BINARY", "REG_NONE", "REG_UNKNOWN"):
        errors.append(f"{where}: {rtype} values are not supported by the undo engine")
    return "" if data is None else str(data)


def collect(root, options):
    registry, services, tasks, used = [], [], [], {}
    seen = {}
    for f in sorted((root / "Configuration" / "Tasks").glob("*.yml")):
        if f.name == "converge.yml":
            continue
        doc = yaml.load(f.read_text(encoding="utf-8-sig"), Loader=Loader) or {}
        file_option = doc.get("option")
        for a in doc.get("actions") or []:
            if not isinstance(a, TaggedAction):
                continue
            where = f"{f.relative_to(root)}:{a.line}"
            p = a.params
            opt = p.get("option") or file_option
            if opt and str(opt).startswith("!"):
                errors.append(f"{where}: negated options are only for converge.yml")
                continue
            if p.get("options"):
                errors.append(f"{where}: 'options' lists are not supported by the undo engine; use one option")
                continue
            group = opt or f.stem
            if opt and opt not in options:
                errors.append(f"{where}: option '{opt}' is not on any feature page")

            if a.tag in NOT_REVERSIBLE:
                errors.append(f"{where}: !{a.tag} {NOT_REVERSIBLE[a.tag]}, which the toolbox cannot undo")
            elif a.tag == "service":
                op = p.get("operation", "delete")
                if op != "change":
                    if op in ("delete",):
                        errors.append(f"{where}: !service {op} cannot be undone; use operation: change")
                    continue
                services.append({"group": group, "name": p["name"], "startup": int(p["startup"])})
                used[group] = True
            elif a.tag == "scheduledTask":
                op = p.get("operation", "delete")
                if op in ("delete", "deleteFolder"):
                    errors.append(f"{where}: !scheduledTask {op} cannot be undone; use operation: disable")
                    continue
                if "data" in p:
                    errors.append(f"{where}: !scheduledTask with XML data cannot be undone")
                    continue
                tasks.append({"group": group, "path": p["path"], "operation": op})
                used[group] = True
            elif a.tag == "registryValue":
                path = p["path"].strip().rstrip("\\")
                if re.match(r"(HKU|HKEY_USERS)\\", path, re.I):
                    errors.append(f"{where}: write HKCU with a scope instead of HKU paths")
                    continue
                name = p.get("value", "")
                op = "delete" if p.get("operation") == "delete" else "set"
                hkcu = re.match(r"(HKCU|HKEY_CURRENT_USER)\\", path, re.I) is not None
                scope = p.get("scope", "allUsers") if hkcu else ""
                rtype = p.get("type", "")
                entry = {"group": group, "path": path, "name": name, "scope": scope,
                         "type": rtype if op == "set" else "",
                         "data": norm_data(rtype, p.get("data"), where) if op == "set" else None,
                         "operation": op, "observeOnly": False}
                key = (path.lower(), name.lower(), scope)
                if key in seen:
                    errors.append(f"{where}: {path}\\{name} is also set at {seen[key]}; one owner per value")
                    continue
                seen[key] = where
                registry.append(entry)
                used[group] = True
            elif opt or a.tag in ("cmd", "powerShell", "run", "appx"):
                used.setdefault(group, False)
    for o in OBSERVE_ONLY:
        registry.append({"group": o["group"], "path": o["path"], "name": o["name"], "scope": "",
                         "type": o["type"], "data": None, "operation": "observe", "observeOnly": True})
    return registry, services, tasks, used


def title_for(group, options):
    if group in TITLES:
        return TITLES[group]
    return options.get(group, group.replace("-", " ").capitalize())


def file_title(title):
    t = re.sub(r"\s*\(.*?\)", "", title)          # drop parentheses
    t = re.sub(r'[\\/:*?"<>|,.]+', " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t[:60].rstrip()


def build(root):
    options = load_options(root)
    registry, services, tasks, used = collect(root, options)
    groups = {}
    for g, has_data in used.items():
        undoable = has_data or g in HANDLERS
        if not undoable:
            continue
        groups[g] = {"title": title_for(g, options), "option": g in options}

    manifest = {
        "comment": "Generated by tools/manifest.py from Configuration/Tasks. Do not edit.",
        "groups": groups,
        "registry": registry,
        "services": services,
        "tasks": tasks,
    }

    launchers = {}
    for g, info in groups.items():
        name = f"Undo - {file_title(info['title'])}.cmd"
        if name in launchers:
            errors.append(f"two groups would share the launcher name '{name}'")
        launchers[name] = ("@echo off\r\n"
                           f"rem {info['title']}\r\n"
                           "powershell.exe -NoProfile -ExecutionPolicy Bypass -File "
                           f"\"%~dp0..\\Internal\\Restore.ps1\" -Group {g}\r\n")

    lines = [GENERATED_HEADER.rstrip("\n"),
             "title: Converge",
             "description: >-",
             "  Undoes options that were on in an earlier run and are off now. Values",
             "  changed by hand since then are left alone.",
             "actions:"]
    converge = [g for g, info in groups.items() if info["option"] and
                (used.get(g) or g in CONVERGE_HANDLERS)]
    if converge:
        lines.append("  - !status: {status: 'Undoing options you turned off'}")
    for g in converge:
        lines.append("  - !powerShell: {command: '& $env:windir\\ClaudePlaybook\\Internal\\Restore.ps1 "
                     f"-Group {g} -OnlyIfUnchanged -Silent; exit $LASTEXITCODE', wait: true, "
                     f"handleExitCodes: {{1: log}}, option: '!{g}'}}")
    if not converge:
        lines[-1] = "actions: []"
    converge_yml = "\n".join(lines) + "\n"
    manifest_json = json.dumps(manifest, indent=2) + "\n"
    return manifest_json, launchers, converge_yml


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    repo = Path(__file__).resolve().parent.parent
    root = Path(args[0]) if args else repo / "playbook"
    manifest_json, launchers, converge_yml = build(root)
    if errors:
        for e in errors:
            print(f"error: {e}")
        sys.exit(1)

    toolbox = root / "Executables" / "ClaudePlaybook"
    undo_dir = toolbox / "Undo one change"
    targets = {toolbox / "Internal" / "manifest.json": manifest_json,
               root / "Configuration" / "Tasks" / "converge.yml": converge_yml}
    for name, text in launchers.items():
        targets[undo_dir / name] = text
    stale = [p for p in (undo_dir.glob("*.cmd") if undo_dir.is_dir() else [])
             if p not in targets]

    if check:
        bad = [p for p, t in targets.items()
               if not p.is_file() or p.read_bytes() != t.encode("utf-8")] + stale
        for p in bad:
            print(f"out of date: {p.relative_to(root)}")
        if bad:
            sys.exit("run python3 tools/manifest.py and commit the result")
        print("manifest, launchers and converge.yml are up to date")
        return

    for p in stale:
        p.unlink()
    for p, t in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(t.encode("utf-8"))
    print(f"wrote manifest ({len(json.loads(manifest_json)['registry'])} registry values), "
          f"{len(launchers)} undo launchers and converge.yml")


if __name__ == "__main__":
    main()
